async function api(path, body, method = body === undefined ? 'GET' : 'POST', expected = true, admin = true) {
  const response = await fetch(origin + '/_emdash/api/' + path, { method, headers: { origin, 'content-type': 'application/json', 'X-EmDash-Request': '1', ...(admin ? { cookie: cookies.join('; ') } : {}) }, body: body === undefined ? undefined : JSON.stringify(body) });
  const result = await response.json();
  if (expected) assert.ok(response.ok && result.success && result.data?.ok !== false, JSON.stringify(result));
  return result.data;
}
